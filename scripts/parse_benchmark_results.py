#!/usr/bin/env python3
"""
vLLM Serving Lab - Benchmark Results Parser & SLA Reporter

Parses raw JSON outputs generated by `vllm bench serve`, aggregates SLA metrics
(throughput, P99 tail latency, error rate), and generates a structured summary report.
"""
import os
import sys
import glob
import json
import argparse
from datetime import datetime, timezone

# Ensure UTF-8 output on Windows consoles
if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8")
if hasattr(sys.stderr, "reconfigure"):
    sys.stderr.reconfigure(encoding="utf-8")


def parse_workload_name(input_len: int, output_len: int) -> str:
    if input_len <= 256 and output_len <= 256:
        return "Short Chat"
    elif input_len >= 1024 and output_len <= 256:
        return "Long Prefill"
    elif output_len >= 500:
        return "Decode Heavy"
    return f"Custom ({input_len}/{output_len})"


def main():
    parser = argparse.ArgumentParser(description="vLLM Benchmark Results Parser")
    parser.add_argument("--result-dir", type=str, default="results/baseline", help="Directory containing benchmark subfolders")
    parser.add_argument("--gpu-name", type=str, default="NVIDIA GPU", help="GPU hardware model")
    parser.add_argument("--driver-version", type=str, default="N/A", help="NVIDIA Driver version")
    parser.add_argument("--model-name", type=str, default="qwen2.5-7b-instruct-fp8", help="Served model name")
    parser.add_argument("--dtype", type=str, default="FP8 (Dynamic)", help="Model weight precision")
    parser.add_argument("--request-rate", type=str, default="inf", help="Traffic request arrival rate")
    parser.add_argument("--burstiness", type=str, default="1.0", help="Arrival burstiness factor")
    args = parser.parse_args()

    result_dir = args.result_dir
    if not os.path.isdir(result_dir):
        print(f"❌ Error: Result directory '{result_dir}' not found.")
        sys.exit(1)

    # Determine distribution description
    if args.request_rate == "inf":
        distribution_desc = "Saturated / Closed-loop (Burst: inf RPS)"
    elif float(args.burstiness) == 1.0:
        distribution_desc = f"Poisson Arrival Process ({args.request_rate} RPS, burstiness=1.0)"
    else:
        distribution_desc = f"Gamma Arrival Process ({args.request_rate} RPS, burstiness={args.burstiness})"

    subdirs = sorted([
        d for d in os.listdir(result_dir)
        if os.path.isdir(os.path.join(result_dir, d)) and d.startswith("in")
    ])

    if not subdirs:
        print(f"⚠️  No workload result folders found in {result_dir}")
        sys.exit(0)

    rows = []
    total_completed_all = 0
    total_failed_all = 0

    for sub in subdirs:
        sub_path = os.path.join(result_dir, sub)
        # Find latest json file in this subfolder
        json_files = sorted(glob.glob(os.path.join(sub_path, "*.json")), key=os.path.getmtime)
        if not json_files:
            continue
        latest_file = json_files[-1]

        try:
            with open(latest_file, "r", encoding="utf-8") as f:
                data = json.load(f)
        except Exception as e:
            print(f"⚠️ Failed reading {latest_file}: {e}")
            continue

        # Extract dimensions
        in_len = data.get("random_input_len") or data.get("input_lens", [0])[0] if data.get("input_lens") else 0
        out_len = data.get("random_output_len") or data.get("output_lens", [0])[0] if data.get("output_lens") else 0
        concurrency = data.get("max_concurrency", 1)
        workload = parse_workload_name(in_len, out_len)

        # Performance metrics
        output_tps = data.get("output_throughput", 0.0)
        qps = data.get("request_throughput", 0.0)
        p99_ttft = data.get("p99_ttft_ms", 0.0)
        p99_tpot = data.get("p99_tpot_ms", 0.0)
        mean_ttft = data.get("mean_ttft_ms", 0.0)
        mean_tpot = data.get("mean_tpot_ms", 0.0)

        # Reliability metrics
        completed = data.get("completed", 0)
        failed = data.get("failed", 0)
        total_reqs = completed + failed
        error_rate = (failed / total_reqs * 100) if total_reqs > 0 else 0.0
        status = "PASS" if error_rate == 0.0 else f"FAIL ({error_rate:.1f}%)"

        total_completed_all += completed
        total_failed_all += failed

        rows.append({
            "workload": workload,
            "in_len": in_len,
            "out_len": out_len,
            "concurrency": concurrency,
            "output_tps": round(output_tps, 1),
            "qps": round(qps, 2),
            "p99_ttft_ms": round(p99_ttft, 1),
            "p99_tpot_ms": round(p99_tpot, 1),
            "mean_ttft_ms": round(mean_ttft, 1),
            "mean_tpot_ms": round(mean_tpot, 1),
            "completed": completed,
            "failed": failed,
            "error_rate_pct": round(error_rate, 2),
            "status": status,
        })

    # Sort rows by workload and concurrency
    rows.sort(key=lambda r: (r["workload"], r["concurrency"]))

    # Overall summary stats
    all_reqs = total_completed_all + total_failed_all
    overall_err_pct = (total_failed_all / all_reqs * 100) if all_reqs > 0 else 0.0
    overall_status = "PASS" if overall_err_pct == 0.0 else f"FAIL ({overall_err_pct:.1f}%)"

    # Print Terminal Table
    print("\n" + "=" * 94)
    print("           📊 vLLM Serving Lab - Comprehensive Benchmark SLA Report")
    print("=" * 94)
    print(f"🖥️  GPU Hardware       : {args.gpu_name} (Driver: {args.driver_version})")
    print(f"🤖 Model & Precision   : {args.model_name} | Dtype: {args.dtype}")
    print(f"📈 Arrival Distribution: {distribution_desc}")
    print(f"🎯 Total Requests Run  : {all_reqs} ({total_completed_all} Completed, {total_failed_all} Failed)")
    print(f"🛡️ Overall Error Rate  : {overall_err_pct:.2f}% [{overall_status}]")
    print("-" * 94)
    printf_fmt = "%-14s  %-10s  %-6s  %13s  %11s  %11s  %11s  %8s\n"
    print(printf_fmt % (
        "Workload", "In/Out Len", "Conc", "Throughput", "P99 TTFT", "P99 TPOT", "Error Rate", "Status"
    ), end="")
    print(printf_fmt % (
        "--------------", "----------", "------", "-------------", "-----------", "-----------", "-----------", "--------"
    ), end="")

    for r in rows:
        in_out_str = f"{r['in_len']}/{r['out_len']}"
        tps_str = f"{r['output_tps']:.1f} tok/s"
        ttft_str = f"{r['p99_ttft_ms']:.1f} ms"
        tpot_str = f"{r['p99_tpot_ms']:.1f} ms"
        err_str = f"{r['error_rate_pct']:.1f}% ({r['failed']}/{r['completed'] + r['failed']})"
        conc_str = f"c={r['concurrency']}"
        print(printf_fmt % (
            r['workload'], in_out_str, conc_str, tps_str, ttft_str, tpot_str, err_str, r['status']
        ), end="")

    print("=" * 94)

    # Save JSON summary report
    summary_data = {
        "timestamp": datetime.now(timezone.utc).isoformat(),
        "hardware": {
            "gpu_name": args.gpu_name,
            "driver_version": args.driver_version,
        },
        "model": {
            "model_name": args.model_name,
            "precision_dtype": args.dtype,
        },
        "traffic_pattern": {
            "request_rate": args.request_rate,
            "burstiness": args.burstiness,
            "distribution_description": distribution_desc,
        },
        "sla_summary": {
            "total_requests": all_reqs,
            "total_completed": total_completed_all,
            "total_failed": total_failed_all,
            "overall_error_rate_pct": round(overall_err_pct, 2),
            "overall_status": overall_status,
        },
        "benchmarks": rows,
    }

    summary_file = os.path.join(result_dir, "summary.json")
    with open(summary_file, "w", encoding="utf-8") as f:
        json.dump(summary_data, f, indent=2, ensure_ascii=False)
    print(f"📁 Structured JSON Summary Report written to: {summary_file}\n")


if __name__ == "__main__":
    main()
